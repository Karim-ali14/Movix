package com.karimali.movix.core.ui.theme


import androidx.compose.ui.unit.dp

/**
 * Spacing scale on Material's 4dp grid. Screens pick a step, not a number:
 *   AppSpacing.md   // default gap between related items
 *   AppSpacing.lg   // page padding and gap between sections
 */
object AppSpacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
}